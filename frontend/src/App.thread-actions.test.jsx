import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { act, cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import App from './App';
import { installSelectionPaneR1Fixture, R1 } from './test/selectionPaneR1Fixture';
import { setActiveEnvironment } from './utils/remoteEnvironments';

describe('App thread rename recovery', () => {
  let fixture;
  let log;

  beforeEach(() => {
    fixture = installSelectionPaneR1Fixture();
    log = vi.spyOn(console, 'error').mockImplementation(() => {});
  });

  afterEach(() => {
    cleanup();
    fixture.restore();
    log.mockRestore();
  });

  it.each(['title', 'topic', 'malformed', 'mismatched'])('retains the draft after a failed %s update and retries only the remaining work', async failureStage => {
    const title = 'Recovered synthetic thread';
    const titleFailure = failureStage !== 'topic';
    const endpoint = `/api/structured/sessions/${R1.a.id}`;
    const writes = [];
    const attempts = {title: 0, topic: 0};
    const fixtureFetch = globalThis.fetch;
    let snapshot = {
      id: R1.a.id, title: R1.a.topic, provider: R1.provider, model: R1.model,
      runtime: 'v4', status: 'idle', cwd: R1.cwd,
      createdAt: '2026-10-17T10:00:00Z', updatedAt: '2026-10-17T10:00:00Z',
      thread: {topic: R1.a.topic, projectPath: R1.cwd, pinned: false, archived: false},
      latestSeq: 0, statusSeq: 0,
    };
    vi.stubGlobal('fetch', async (input, options = {}) => {
      const url = new URL(String(input), location.href);
      const isTitle = url.pathname.endsWith(endpoint);
      const isTopic = url.pathname.endsWith(`${endpoint}/thread`);
      if (options.method === 'PATCH' && (isTitle || isTopic)) {
        const stage = isTitle ? 'title' : 'topic';
        attempts[stage] += 1;
        const body = JSON.parse(options.body);
        writes.push({stage, body});
        if (stage === 'title' && attempts[stage] === 1 && failureStage === 'malformed') {
          return new Response('{}', {status: 200});
        }
        if (stage === 'title' && attempts[stage] === 1 && failureStage === 'mismatched') {
          return new Response(JSON.stringify({...snapshot, id: 'ss-wrong', title}), {status: 200});
        }
        if (stage === failureStage && attempts[stage] === 1) {
          return new Response(JSON.stringify({error: 'Synthetic write failure'}), {status: 503});
        }
        snapshot = isTitle ? {...snapshot, title: body.title} : {...snapshot, thread: {...snapshot.thread, ...body}};
        return new Response(JSON.stringify(isTitle ? snapshot : {thread: snapshot.thread}), {status: 200});
      }
      return fixtureFetch(input, options);
    });

    render(<App />);
    fireEvent.change(await screen.findByLabelText('Username'), {target: {value: R1.username}});
    fireEvent.change(screen.getByLabelText('Password'), {target: {value: R1.password}});
    fireEvent.click(screen.getByRole('button', {name: 'Initialize Session'}));
    await waitFor(() => expect(document.querySelector('.threads-card')).toBeInTheDocument());
    fireEvent.click(await screen.findByRole('button', {name: `Thread actions for ${R1.a.topic}`}));
    fireEvent.click(screen.getByRole('menuitem', {name: 'Rename session'}));
    const input = screen.getByRole('textbox', {name: 'Thread title'});
    fireEvent.change(input, {target: {value: title}});
    fireEvent.keyDown(input, {key: 'Enter'});
    expect(await screen.findByRole('alert')).toHaveTextContent(titleFailure ? 'may have been saved' : '503');
    expect(input).toHaveValue(title);
    expect(writes).toEqual(titleFailure
      ? [{stage: 'title', body: {title}}]
      : [{stage: 'title', body: {title}}, {stage: 'topic', body: {topic: title, topicAutoGenerated: false}}]);

    fireEvent.click(screen.getByRole('button', {name: 'Retry'}));
    if (titleFailure) {
      expect(await screen.findByRole('alert')).toHaveTextContent('Review it before saving again');
      expect(writes).toEqual([{stage: 'title', body: {title}}]);
      fireEvent.click(screen.getByRole('button', {name: 'Retry'}));
    }
    await waitFor(() => expect(screen.queryByRole('textbox', {name: 'Thread title'})).not.toBeInTheDocument());
    expect(screen.getByRole('button', {name: `Select ${title}`})).toBeInTheDocument();
    expect(screen.queryByRole('alert')).not.toBeInTheDocument();
    expect(writes).toEqual(titleFailure
      ? [{stage: 'title', body: {title}}, {stage: 'title', body: {title}}, {stage: 'topic', body: {topic: title, topicAutoGenerated: false}}]
      : [{stage: 'title', body: {title}}, {stage: 'topic', body: {topic: title, topicAutoGenerated: false}}, {stage: 'topic', body: {topic: title, topicAutoGenerated: false}}]);
    expect(fixture.sendCalls()).toEqual([]);
    expect(fixture.socketWrites).toEqual([]);
    expect(fixture.unexpected).toEqual([]);
  });

  it('does not send a topic update to a new environment after a delayed title response', async () => {
    const endpoint = `/api/structured/sessions/${R1.a.id}`;
    const fixtureFetch = globalThis.fetch;
    const writes = [];
    let finishRename;
    vi.stubGlobal('fetch', async (input, options = {}) => {
      const url = new URL(String(input), location.href);
      if (options.method === 'PATCH' && (url.pathname.endsWith(endpoint) || url.pathname.endsWith(`${endpoint}/thread`))) {
        writes.push(url.pathname.endsWith('/thread') ? 'topic' : 'title');
        if (url.pathname.endsWith(endpoint)) return new Promise(resolve => { finishRename = resolve; });
      }
      return fixtureFetch(input, options);
    });
    render(<App />);
    fireEvent.change(await screen.findByLabelText('Username'), {target: {value: R1.username}});
    fireEvent.change(screen.getByLabelText('Password'), {target: {value: R1.password}});
    fireEvent.click(screen.getByRole('button', {name: 'Initialize Session'}));
    await waitFor(() => expect(document.querySelector('.threads-card')).toBeInTheDocument());
    fireEvent.click(await screen.findByRole('button', {name: `Thread actions for ${R1.a.topic}`}));
    fireEvent.click(screen.getByRole('menuitem', {name: 'Rename session'}));
    const input = screen.getByRole('textbox', {name: 'Thread title'});
    fireEvent.change(input, {target: {value: 'Old environment title'}});
    fireEvent.keyDown(input, {key: 'Enter'});
    await waitFor(() => expect(finishRename).toBeTypeOf('function'));
    act(() => setActiveEnvironment({id: 'other-environment'}));
    await act(async () => finishRename(new Response(JSON.stringify({
      id: R1.a.id, title: 'Old environment title', provider: R1.provider, model: R1.model,
      runtime: 'v4', status: 'idle', cwd: R1.cwd, thread: {topic: R1.a.topic},
    }), {status: 200})));
    expect(writes).toEqual(['title']);
  });

  it('shows the structured title byte limit without sending a desktop rename', async () => {
    const endpoint = `/api/structured/sessions/${R1.a.id}`;
    const fixtureFetch = globalThis.fetch;
    const writes = [];
    vi.stubGlobal('fetch', async (input, options = {}) => {
      const url = new URL(String(input), location.href);
      if (options.method === 'PATCH' && url.pathname.startsWith(endpoint)) writes.push(url.pathname);
      return fixtureFetch(input, options);
    });
    render(<App />);
    fireEvent.change(await screen.findByLabelText('Username'), {target: {value: R1.username}});
    fireEvent.change(screen.getByLabelText('Password'), {target: {value: R1.password}});
    fireEvent.click(screen.getByRole('button', {name: 'Initialize Session'}));
    await waitFor(() => expect(document.querySelector('.threads-card')).toBeInTheDocument());
    fireEvent.click(await screen.findByRole('button', {name: `Thread actions for ${R1.a.topic}`}));
    fireEvent.click(screen.getByRole('menuitem', {name: 'Rename session'}));
    const input = screen.getByRole('textbox', {name: 'Thread title'});
    fireEvent.change(input, {target: {value: '😀'.repeat(21)}});
    fireEvent.keyDown(input, {key: 'Enter'});
    expect(await screen.findByRole('alert')).toHaveTextContent('80 UTF-8 bytes');
    expect(input).toHaveValue('😀'.repeat(21));
    expect(writes).toEqual([]);
  });

  it('shows the structured title byte limit without sending a mobile rename', async () => {
    const width = Object.getOwnPropertyDescriptor(window, 'innerWidth');
    const viewport = Object.getOwnPropertyDescriptor(window, 'visualViewport');
    Object.defineProperty(window, 'innerWidth', { configurable: true, value: 390 });
    Object.defineProperty(window, 'visualViewport', { configurable: true, value: { width: 390, height: 844, addEventListener() {}, removeEventListener() {} } });
    vi.stubGlobal('ResizeObserver', class { observe() {} disconnect() {} });
    const endpoint = `/api/structured/sessions/${R1.a.id}`;
    const fixtureFetch = globalThis.fetch;
    const writes = [];
    vi.stubGlobal('fetch', async (input, options = {}) => {
      const url = new URL(String(input), location.href);
      if (options.method === 'PATCH' && url.pathname.startsWith(endpoint)) writes.push(url.pathname);
      return fixtureFetch(input, options);
    });
    try {
      render(<App />);
      fireEvent.change(await screen.findByLabelText('Username'), {target: {value: R1.username}});
      fireEvent.change(screen.getByLabelText('Password'), {target: {value: R1.password}});
      fireEvent.click(screen.getByRole('button', {name: 'Initialize Session'}));
      fireEvent.click(await screen.findByRole('button', {name: 'More actions', exact: true}));
      fireEvent.click(await screen.findByRole('button', {name: 'Rename thread', exact: true}));
      const dialog = screen.getByRole('dialog', {name: 'Rename thread'});
      const input = within(dialog).getByRole('textbox', {name: 'Thread title'});
      fireEvent.change(input, {target: {value: '😀'.repeat(21)}});
      fireEvent.click(within(dialog).getByRole('button', {name: 'Save'}));
      expect(await within(dialog).findByRole('alert')).toHaveTextContent('80 UTF-8 bytes');
      expect(input).toHaveValue('😀'.repeat(21));
      expect(writes).toEqual([]);
    } finally {
      if (width) Object.defineProperty(window, 'innerWidth', width);
      if (viewport) Object.defineProperty(window, 'visualViewport', viewport);
      else delete window.visualViewport;
    }
  });

  it.each(['desktop', 'mobile'])('sends a complete emoji at the 60-character boundary on %s', async view => {
    const width = Object.getOwnPropertyDescriptor(window, 'innerWidth');
    const viewport = Object.getOwnPropertyDescriptor(window, 'visualViewport');
    if (view === 'mobile') {
      Object.defineProperty(window, 'innerWidth', { configurable: true, value: 390 });
      Object.defineProperty(window, 'visualViewport', { configurable: true, value: { width: 390, height: 844, addEventListener() {}, removeEventListener() {} } });
      vi.stubGlobal('ResizeObserver', class { observe() {} disconnect() {} });
    }
    const title = `${'a'.repeat(59)}😀`;
    const endpoint = `/api/structured/sessions/${R1.a.id}`;
    const fixtureFetch = globalThis.fetch;
    const writes = [];
    vi.stubGlobal('fetch', async (input, options = {}) => {
      const url = new URL(String(input), location.href);
      if (options.method === 'PATCH' && url.pathname === endpoint) {
        const body = JSON.parse(options.body);
        writes.push(body);
        return new Response(JSON.stringify({ id: R1.a.id, title: body.title, provider: R1.provider, runtime: 'v4', cwd: R1.cwd, thread: {topic: R1.a.topic} }), {status: 200});
      }
      return fixtureFetch(input, options);
    });
    try {
      render(<App />);
      fireEvent.change(await screen.findByLabelText('Username'), {target: {value: R1.username}});
      fireEvent.change(screen.getByLabelText('Password'), {target: {value: R1.password}});
      fireEvent.click(screen.getByRole('button', {name: 'Initialize Session'}));
      if (view === 'mobile') {
        fireEvent.click(await screen.findByRole('button', {name: 'More actions', exact: true}));
        fireEvent.click(await screen.findByRole('button', {name: 'Rename thread', exact: true}));
        const dialog = screen.getByRole('dialog', {name: 'Rename thread'});
        fireEvent.change(within(dialog).getByRole('textbox', {name: 'Thread title'}), {target: {value: title}});
        fireEvent.click(within(dialog).getByRole('button', {name: 'Save'}));
      } else {
        fireEvent.click(await screen.findByRole('button', {name: `Thread actions for ${R1.a.topic}`}));
        fireEvent.click(screen.getByRole('menuitem', {name: 'Rename session'}));
        const input = screen.getByRole('textbox', {name: 'Thread title'});
        fireEvent.change(input, {target: {value: title}});
        fireEvent.keyDown(input, {key: 'Enter'});
      }
      await waitFor(() => expect(writes).toEqual([{title}]));
    } finally {
      if (width) Object.defineProperty(window, 'innerWidth', width);
      if (viewport) Object.defineProperty(window, 'visualViewport', viewport);
      else delete window.visualViewport;
    }
  });
});
