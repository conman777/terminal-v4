import { describe, expect, it } from 'vitest';
import { buildStructuredSession, mergeSessionCollections } from './structuredSessions';

describe('structured session inventory', () => {
  it('preserves server lifecycle state only when the capability is complete', () => {
    const lifecycle = { supported: true, snoozed: true, requiresAttention: false, snoozedUntilMs: 12345 };
    expect(buildStructuredSession({ id: 'ss-one', threadLifecycle: lifecycle }).threadLifecycle).toEqual(lifecycle);
    expect(buildStructuredSession({ id: 'ss-old' })).not.toHaveProperty('threadLifecycle');
    expect(buildStructuredSession({ id: 'ss-incomplete', threadLifecycle: { supported: true, snoozed: true } })).not.toHaveProperty('threadLifecycle');
  });
  it.each([
    ['accepted', true], ['running', true], ['idle', false], ['completed', false],
    ['failed', false], ['cancelled', false], ['interrupted', false],
    ['cleanup_required', false], ['reconciliation_required', false],
  ])('maps authoritative lifecycle status %s to busy=%s', (status, isBusy) => {
    expect(buildStructuredSession({ id: 'ss-inventory', provider: 'codex', status, statusSeq: 3 })).toMatchObject({ status, statusSeq: 3, isBusy });
  });

  it('does not invent a busy state for absent or unknown lifecycle status', () => {
    expect(buildStructuredSession({ id: 'ss-legacy' })).not.toHaveProperty('isBusy');
    expect(buildStructuredSession({ id: 'ss-unknown', status: 'new_status' })).not.toHaveProperty('isBusy');
  });
  it.each([
    [{ statusSeq: 42, latestSeq: 45 }, 42],
    [{ latestSeq: 45 }, 45],
    [{ statusSeq: 0, latestSeq: 45 }, 0],
    [{ statusSeq: -1, latestSeq: 45 }, 45],
    [{ statusSeq: '42', latestSeq: 45 }, 45],
    [{ statusSeq: 1.5, latestSeq: Number.MAX_SAFE_INTEGER + 1 }, 8],
    [{}, 8],
  ])('preserves the authoritative lifecycle watermark for %j', (sequences, statusSeq) => {
    const session = buildStructuredSession({
      id: 'ss-inventory', runtime: 'codex', status: 'cleanup_required',
      events: [{ seq: 3 }, { seq: 8 }, { seq: 5 }], ...sequences,
    });

    expect(session).toMatchObject({ id: 'ss-inventory', runtime: 'codex', status: 'cleanup_required', statusSeq });
  });

  it('maps metadata-only inventory without reading conversation events', () => {
    const inventory = {
      id: 'ss-inventory', provider: 'codex', runtime: 'codex', title: 'Inventory thread',
      cwd: '/fixture/workspace', model: 'fixture-model', reasoning: 'high',
      status: 'idle', statusSeq: 27, latestSeq: 27,
      createdAt: '2026-10-20T09:00:00.000Z', updatedAt: '2026-10-20T09:05:00.000Z',
      thread: { topic: 'Review inventory', pinned: true, archived: false, projectPath: '/fixture/project' },
    };
    Object.defineProperty(inventory, 'events', { get() { throw new Error('Inventory must not require transcript events'); } });

    expect(buildStructuredSession(inventory)).toMatchObject({
      id: 'ss-inventory', title: 'Inventory thread', aiType: 'codex', runtime: 'codex',
      cwd: '/fixture/workspace', groupPath: '/fixture/project', model: 'fixture-model', reasoning: 'high',
      status: 'idle', statusSeq: 27,
      thread: { topic: 'Review inventory', pinned: true, archived: false, projectPath: '/fixture/project' },
    });
  });

  it('does not inspect legacy events when no lifecycle status is supplied', () => {
    const snapshot = { id: 'ss-legacy', provider: 'claude' };
    Object.defineProperty(snapshot, 'events', { get() { throw new Error('No lifecycle watermark is needed'); } });

    expect(buildStructuredSession(snapshot)).not.toHaveProperty('statusSeq');
  });

  it('sorts metadata-only conversations with terminals and retains legacy local metadata', () => {
    const sessions = mergeSessionCollections(
      [{ id: 'terminal-fixture', updatedAt: '2026-10-20T09:00:00.000Z' }],
      [{ id: 'ss-inventory', provider: 'codex', cwd: '/fixture/workspace', updatedAt: '2026-10-20T09:05:00.000Z', status: 'idle', latestSeq: 12 }],
      { 'ss-inventory': { title: 'Saved title', thread: { topic: 'Saved topic', pinned: true, projectPath: '/fixture/project' } } },
    );

    expect(sessions.map(session => ({ id: session.id, title: session.title, statusSeq: session.statusSeq, thread: session.thread }))).toEqual([
      { id: 'ss-inventory', title: 'Saved title', statusSeq: 12, thread: { topic: 'Saved topic', pinned: true, archived: false, topicAutoGenerated: false, projectPath: '/fixture/project', lastActivityAt: '2026-10-20T09:05:00.000Z' } },
      { id: 'terminal-fixture', title: undefined, statusSeq: undefined, thread: undefined },
    ]);
  });
});
