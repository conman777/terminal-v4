import { getAiProvider } from './aiProviders';

export const structuredSessionOrigin = Symbol('structured session');

function resolveSessionTimestamp(value) {
  const timestamp = Date.parse(value || '');
  return Number.isFinite(timestamp) ? timestamp : 0;
}

export function isStructuredSessionId(sessionId) {
  return typeof sessionId === 'string' && sessionId.startsWith('ss-');
}

export function getStructuredAgentLabel(session) {
  if (session?.runtime === 'codex') return 'Codex';
  if (session?.runtime === 'v4') return 'V4';
  return getAiProvider(session?.aiType)?.label ?? 'Agent';
}

export function getComposerPlaceholder({ isStructuredSession, session, foregroundAiType, customProviders = [] }) {
  if (isStructuredSession) return `Message ${getStructuredAgentLabel(session)}…`;
  const agentLabel = getAiProvider(foregroundAiType, customProviders)?.label;
  return agentLabel ? `Message ${agentLabel}…` : 'Type a terminal command…';
}

export function buildStructuredSession(snapshot, metadata = {}) {
  const provider = getAiProvider(snapshot?.provider);
  const providerTitle = provider?.title ?? provider?.label ?? 'Structured session';
  const updatedAt = snapshot?.updatedAt || snapshot?.createdAt || new Date(0).toISOString();
  const snapshotThread = snapshot?.thread && typeof snapshot.thread === 'object'
    ? snapshot.thread
    : {};
  const threadMetadata = metadata?.thread && typeof metadata.thread === 'object'
    ? metadata.thread
    : {};
  const title = snapshot?.title || metadata?.title || providerTitle;
  const projectPath = snapshotThread.projectPath ?? threadMetadata.projectPath ?? snapshot?.cwd ?? '';
  const lastActivityAt = snapshotThread.lastActivityAt ?? threadMetadata.lastActivityAt ?? updatedAt;
  const statusSeq = snapshot?.status
    ? ([snapshot.statusSeq, snapshot.latestSeq].find(seq => Number.isSafeInteger(seq) && seq >= 0)
      ?? (Array.isArray(snapshot.events) ? snapshot.events : [])
        .reduce((seq, event) => Number.isSafeInteger(event?.seq) ? Math.max(seq, event.seq) : seq, 0))
    : 0;
  const status = snapshot?.status;
  const busy = ['accepted', 'running'].includes(status) ? true
    : ['idle', 'completed', 'failed', 'cancelled', 'interrupted', 'cleanup_required', 'reconciliation_required'].includes(status) ? false
      : undefined;

  return {
    [structuredSessionOrigin]: true,
    id: snapshot?.id ?? '',
    title,
    shell: snapshot?.provider ?? 'structured',
    aiType: snapshot?.provider ?? null,
    ...(snapshot?.runtime ? { runtime: snapshot.runtime } : {}),
    ...(snapshot?.status ? { status: snapshot.status, statusSeq } : {}),
    ...(typeof busy === 'boolean' ? { isBusy: busy } : {}),
    ...(snapshot?.threadLifecycle?.supported === true
      && typeof snapshot.threadLifecycle.snoozed === 'boolean'
      && typeof snapshot.threadLifecycle.requiresAttention === 'boolean'
      && (!snapshot.threadLifecycle.snoozed || Number.isSafeInteger(snapshot.threadLifecycle.snoozedUntilMs))
      ? { threadLifecycle: snapshot.threadLifecycle } : {}),
    ...(snapshot?.model ? { model: snapshot.model } : {}),
    ...(snapshot?.reasoning ? { reasoning: snapshot.reasoning } : {}),
    ...(snapshot?.serviceTier === null || typeof snapshot?.serviceTier === 'string' ? { serviceTier: snapshot.serviceTier } : {}),
    ...(typeof snapshot?.accessMode === 'string' ? { accessMode: snapshot.accessMode } : {}),
    cwd: snapshot?.cwd ?? '',
    groupPath: projectPath,
    workspaceRoot: snapshot?.cwd ?? '',
    isActive: true,
    usesTmux: false,
    createdAt: snapshot?.createdAt ?? updatedAt,
    updatedAt,
    lastActivityAt,
    thread: {
      pinned: Boolean(snapshotThread.pinned ?? threadMetadata.pinned),
      archived: Boolean(snapshotThread.archived ?? threadMetadata.archived),
      topic: snapshotThread.topic ?? threadMetadata.topic ?? title,
      topicAutoGenerated: Boolean(snapshotThread.topicAutoGenerated ?? threadMetadata.topicAutoGenerated),
      projectPath,
      lastActivityAt,
      ...(snapshotThread.snooze ? { snooze: snapshotThread.snooze } : {}),
    },
  };
}

export function mergeSessionCollections(
  terminalSessions = [],
  structuredSnapshots = [],
  structuredMetadata = {}
) {
  const mappedStructuredSessions = (Array.isArray(structuredSnapshots) ? structuredSnapshots : [])
    .map((snapshot) => buildStructuredSession(snapshot, structuredMetadata?.[snapshot?.id]));

  return [...(Array.isArray(terminalSessions) ? terminalSessions : []), ...mappedStructuredSessions]
    .sort((left, right) => {
      const leftTimestamp = resolveSessionTimestamp(left?.thread?.lastActivityAt || left?.updatedAt);
      const rightTimestamp = resolveSessionTimestamp(right?.thread?.lastActivityAt || right?.updatedAt);
      return rightTimestamp - leftTimestamp;
    });
}

export function normalizeStructuredMessageInput(data) {
  const payload = typeof data === 'string' ? data : String(data ?? '');
  const normalized = payload.replace(/\r\n/g, '\n').replace(/[\r\n]+$/g, '');
  return normalized.trim() ? normalized : '';
}
