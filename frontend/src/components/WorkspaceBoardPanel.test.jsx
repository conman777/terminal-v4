import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { act, fireEvent, render, screen, waitFor, cleanup } from '@testing-library/react';
import { WorkspaceBoardPanel } from './WorkspaceBoardPanel';
import { apiFetch } from '../utils/api';
import { clearTokens, setUser } from '../utils/auth';
vi.mock('../utils/api', () => ({ apiFetch: vi.fn() }));
const response = (data, status = 200) => ({ ok: status >= 200 && status < 300, status, json: async () => data });
const item = { id: 'task-1', title: 'Existing', description: 'Original', status: 'open', blockedReason: null, revision: 1 };
beforeEach(() => { apiFetch.mockReset(); });
afterEach(cleanup);
describe('WorkspaceBoardPanel', () => {
  it('retries an uncertain create with the same operation', async () => {
    apiFetch.mockResolvedValueOnce(response({ items: [] })).mockRejectedValueOnce(new Error('Network lost')).mockResolvedValueOnce(response(item)).mockResolvedValueOnce(response({ items: [item] }));
    render(<WorkspaceBoardPanel workspacePath="/create" />);
    await screen.findByText('No tasks yet.');
    fireEvent.change(screen.getByLabelText('Title'), { target: { value: 'New task' } });
    fireEvent.click(screen.getByRole('button', { name: 'Add task' }));
    await screen.findByText(/write may have succeeded/);
    fireEvent.click(screen.getByRole('button', { name: 'Retry uncertain write' }));
    await screen.findByRole('button', { name: 'Edit Existing' });
    expect(apiFetch.mock.calls[1][1].body).toEqual(apiFetch.mock.calls[2][1].body);
  });
  it('preserves a draft after a stale revision and requires an explicit rebase', async () => {
    apiFetch.mockResolvedValueOnce(response({ items: [item] })).mockResolvedValueOnce(response({ error: 'Board revision is stale' }, 409)).mockResolvedValueOnce(response({ items: [{ ...item, revision: 2, title: 'Changed elsewhere' }] })).mockResolvedValueOnce(response(item)).mockResolvedValueOnce(response({ items: [item] }));
    render(<WorkspaceBoardPanel workspacePath="/conflict" />);
    fireEvent.click(await screen.findByRole('button', { name: 'Edit Existing' }));
    fireEvent.change(screen.getByLabelText('Title'), { target: { value: 'My draft' } });
    fireEvent.click(screen.getByRole('button', { name: 'Save task' }));
    await screen.findByText('Changed elsewhere');
    expect(screen.getByLabelText('Title')).toHaveValue('My draft');
    expect(screen.getByRole('button', { name: 'Save task' })).toBeDisabled();
    fireEvent.click(screen.getByRole('button', { name: 'Use latest revision for draft' }));
    fireEvent.click(screen.getByRole('button', { name: 'Save task' }));
    await waitFor(() => expect(apiFetch.mock.calls[3][1].body).toMatchObject({ expectedRevision: 2, title: 'My draft' }));
  });
  it('isolates drafts and ignores a delayed load when switching workspace', async () => {
    let resolveOld;
    apiFetch.mockImplementation(url => url.includes('%2Fold') ? new Promise(resolve => { resolveOld = resolve; }) : Promise.resolve(response({ items: [] })));
    const view = render(<WorkspaceBoardPanel workspacePath="/old" />);
    fireEvent.change(screen.getByLabelText('Title'), { target: { value: 'Old draft' } });
    view.rerender(<WorkspaceBoardPanel workspacePath="/new" />);
    await screen.findByText('No tasks yet.');
    await act(async () => { resolveOld(response({ items: [item] })); });
    expect(screen.queryByText('Existing')).not.toBeInTheDocument();
    expect(screen.getByLabelText('Title')).toHaveValue('');
    view.rerender(<WorkspaceBoardPanel workspacePath="/old" />);
    expect(screen.getByLabelText('Title')).toHaveValue('Old draft');
  });
  it('isolates drafts and ignores a delayed load after changing accounts', async () => {
    let resolveOld;
    setUser({ id: 'board-account-a' });
    apiFetch.mockImplementationOnce(() => new Promise(resolve => { resolveOld = resolve; })).mockResolvedValue(response({ items: [] }));
    render(<WorkspaceBoardPanel workspacePath="/account-isolation" />);
    fireEvent.change(screen.getByLabelText('Title'), { target: { value: 'Account A draft' } });
    act(() => setUser({ id: 'board-account-b' }));
    await screen.findByText('No tasks yet.');
    await act(async () => { resolveOld(response({ items: [item] })); });
    expect(screen.queryByText('Existing')).not.toBeInTheDocument();
    expect(screen.getByLabelText('Title')).toHaveValue('');
    act(() => clearTokens(true));
  });
  it('rebases only after an uncertain retry confirms a stale revision', async () => {
    apiFetch.mockResolvedValueOnce(response({ items: [item] })).mockRejectedValueOnce(new Error('Network lost')).mockResolvedValueOnce(response({ error: 'Board revision is stale' }, 409)).mockResolvedValueOnce(response({ items: [{ ...item, revision: 2 }] }));
    render(<WorkspaceBoardPanel workspacePath="/uncertain-stale" />);
    fireEvent.click(await screen.findByRole('button', { name: 'Edit Existing' }));
    fireEvent.change(screen.getByLabelText('Title'), { target: { value: 'My draft' } });
    fireEvent.click(screen.getByRole('button', { name: 'Save task' }));
    fireEvent.click(await screen.findByRole('button', { name: 'Retry uncertain write' }));
    await screen.findByRole('button', { name: 'Use latest revision for draft' });
    expect(screen.queryByRole('button', { name: 'Retry uncertain write' })).not.toBeInTheDocument();
    expect(screen.getByLabelText('Title')).toHaveValue('My draft');
    expect(apiFetch.mock.calls[1][1].body).toEqual(apiFetch.mock.calls[2][1].body);
  });
  it.each(['Board receipt limit reached', 'operationId already used with a different request', 'Board revision exhausted', 'Unknown conflict'])('keeps an uncertain edit pending after %s', async message => {
    apiFetch.mockResolvedValueOnce(response({ items: [item] })).mockRejectedValueOnce(new Error('Network lost')).mockResolvedValueOnce(response({ error: message }, 409));
    render(<WorkspaceBoardPanel workspacePath={'/uncertain-' + message} />);
    fireEvent.click(await screen.findByRole('button', { name: 'Edit Existing' }));
    fireEvent.change(screen.getByLabelText('Title'), { target: { value: 'My draft' } });
    fireEvent.click(screen.getByRole('button', { name: 'Save task' }));
    await screen.findByRole('button', { name: 'Retry uncertain write' });
    fireEvent.click(screen.getByRole('button', { name: 'Retry uncertain write' }));
    await screen.findByText(message);
    expect(screen.getByLabelText('Title')).toHaveValue('My draft');
    expect(screen.getByRole('button', { name: 'Save task' })).toBeDisabled();
    expect(screen.getByRole('button', { name: 'Retry uncertain write' })).toBeEnabled();
    expect(screen.queryByRole('button', { name: 'Use latest revision for draft' })).not.toBeInTheDocument();
    expect(apiFetch.mock.calls[1][1].body).toEqual(apiFetch.mock.calls[2][1].body);
    expect(apiFetch).toHaveBeenCalledTimes(3);
  });
  it('requires explicit confirmation before deleting', async () => {
    apiFetch.mockResolvedValueOnce(response({ items: [item] })).mockResolvedValueOnce(response({ deleted: true })).mockResolvedValueOnce(response({ items: [] }));
    render(<WorkspaceBoardPanel workspacePath="/delete" />);
    await screen.findByRole('button', { name: 'Edit Existing' });
    fireEvent.click(screen.getByText('Delete'));
    expect(apiFetch).toHaveBeenCalledTimes(1);
    fireEvent.click(screen.getByRole('button', { name: 'Confirm delete Existing' }));
    await screen.findByText('No tasks yet.');
    expect(apiFetch.mock.calls[1][1]).toMatchObject({ method: 'DELETE', body: { path: '/delete', expectedRevision: 1 } });
  });
});
