async function threadRenameResponses(page: Page, fixture: Awaited<ReturnType<typeof installFixture>>, title: string, failureStage: 'title' | 'topic') {
  let snapshot = await page.evaluate(async id => (await fetch(`/api/structured/sessions/${id}`, { headers: { Authorization: `Bearer ${localStorage.getItem('terminal_access_token')}` } })).json(), fixture.structuredId);
  const writes: { stage: string; body: unknown }[] = [];
  const attempts = { title: 0, topic: 0 };
  const endpoint = `/api/structured/sessions/${fixture.structuredId}`;
  await page.route('**/api/structured/sessions**', async route => {
    const request = route.request(), pathname = new URL(request.url()).pathname;
    if (request.method() === 'GET' && pathname === '/api/structured/sessions') return route.fulfill({ json: [{ ...snapshot, events: [] }] });
    if (request.method() === 'GET' && pathname === endpoint) return route.fulfill({ json: snapshot });
    if (request.method() !== 'PATCH' || ![endpoint, `${endpoint}/thread`].includes(pathname)) return route.fallback();
    const stage = pathname === endpoint ? 'title' : 'topic';
    const body = request.postDataJSON();
    const expected = stage === 'title' ? { title } : { topic: title, topicAutoGenerated: false };
    if (JSON.stringify(body) !== JSON.stringify(expected)) return route.fallback();
    writes.push({ stage, body }); attempts[stage]++;
    if (stage === failureStage && attempts[stage] === 1) return route.fulfill({ status: 503, json: { error: `Synthetic ${stage} save unavailable.` } });
    snapshot = stage === 'title' ? { ...snapshot, title } : { ...snapshot, thread: { ...snapshot.thread, ...body } };
    return route.fulfill({ json: stage === 'title' ? snapshot : { thread: snapshot.thread } });
  });
  return writes;
}

