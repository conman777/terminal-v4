fn digest(bytes: &[u8]) -> String {
    use sha2::{Digest, Sha256};
    hex::encode(Sha256::digest(bytes))
}
fn mutation_digest(mutation: &Mutation) -> Result<String, QueueError> {
    use sha2::{Digest, Sha256};
    struct HashWriter(Sha256);
    impl std::io::Write for HashWriter {
        fn write(&mut self, bytes: &[u8]) -> std::io::Result<usize> {
            self.0.update(bytes);
            Ok(bytes.len())
        }
        fn flush(&mut self) -> std::io::Result<()> {
            Ok(())
        }
    }
    let mut writer = HashWriter(Sha256::new());
    serde_json::to_writer(&mut writer, mutation)
        .map_err(|_| invalid("Cannot encode queue operation"))?;
    Ok(hex::encode(writer.0.finalize()))
}

fn canonical_authority_root(data: &Path) -> Result<String, QueueError> {
    std::fs::canonicalize(data)
        .map_err(|_| unavailable("Queue data root is unavailable"))?
        .to_str()
        .map(str::to_owned)
        .ok_or_else(|| unavailable("Queue data root must be UTF-8"))
}

fn seal_authority(
    data: &Path,
    scope: &QueueScope,
    queue_identity: Uuid,
    item: &QueueItem,
    input: &AuthorityInput,
    check: Option<&dyn Fn() -> Result<(), String>>,
) -> Result<(String, Option<Uuid>), QueueError> {
    let now = now_ms();
    if now <= 0 || now >= input.expires_at_ms || input.generation < 0 {
        return Err(conflict("Queue authority expired before it was saved"));
    }
    let claims = AuthorityClaims {
        version: 1,
        owner: scope.owner.clone(),
        data_root: canonical_authority_root(data)?,
        workspace: scope
            .workspace
            .to_str()
            .ok_or_else(|| invalid("Workspace must be UTF-8"))?
            .into(),
        parent_session_id: scope.parent_session_id.clone(),
        session_incarnation: input.session_incarnation,
        queue_identity,
        item_id: item.item_id,
        input_request_id: item.input_request_id,
        text_digest: digest(item.text.as_bytes()),
        generation: input.generation,
        expires_at_ms: input.expires_at_ms,
    };
    let encoded =
        serde_json::to_string(&claims).map_err(|_| unavailable("Cannot encode queue authority"))?;
    #[cfg(unix)]
    let (cipher, installation) = authority_installation::load_for_write(data, check)?;
    #[cfg(not(unix))]
    let (cipher, installation) = {
        let _ = check;
        (
            crate::vault::VaultCipher::load_existing(data)
                .map_err(|_| unavailable("Queue authority key is unavailable"))?,
            Uuid::nil(),
        )
    };
    cipher
        .encrypt(&encoded)
        .map(|value| (value, (!installation.is_nil()).then_some(installation)))
        .map_err(|_| unavailable("Cannot protect queue authority"))
}
