    /// The actor must recheck this captured idle epoch before canonical admission.
    pub(crate) fn reserve_next(
        &self,
        scope: &QueueScope,
        expected_queue_revision: u64,
        idle: IdleBoundary,
    ) -> Result<Option<DispatchReservation>, QueueError> {
        let _guard = self.storage_guard()?;
        let _root_guard = self.try_lock_storage_root()?;
        let (path, mut envelope) = self.load_locked(scope)?;
        let queue = &mut envelope.queue;
        if queue.revision != expected_queue_revision {
            return Err(conflict("Queue changed before dispatch reservation"));
        }
        if queue.mode == QueueMode::Held
            || queue
                .items
                .iter()
                .any(|item| item.state == ItemState::Dispatching)
            || queue.order.is_empty()
        {
            return Ok(None);
        }
        let item_id = queue.order.remove(0);
        let item = queue
            .items
            .iter_mut()
            .find(|item| item.item_id == item_id)
            .ok_or_else(|| corrupt("Queue order refers to a missing item"))?;
        if item.state != ItemState::Pending {
            return Err(corrupt("Queue dispatch item is not pending"));
        }
        item.state = ItemState::Dispatching;
        item.revision = increment(item.revision)?;
        item.updated_at = now_ms().max(item.updated_at);
        queue.revision = increment(queue.revision)?;
        let reservation = DispatchReservation {
            item_id,
            item_revision: item.revision,
            input_request_id: item.input_request_id,
            text: item.text.clone(),
            turn_epoch: idle.turn_epoch,
            queue_revision: queue.revision,
        };
        self.commit(&path, &envelope, scope)?;
        Ok(Some(reservation))
    }

