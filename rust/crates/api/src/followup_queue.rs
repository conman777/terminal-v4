/// directory through this function so tests can make confirmation fail.
#[cfg(unix)]
fn sync_directory(path: &Path) -> std::io::Result<()> {
    #[cfg(test)]
    if fault::directory_sync_fails() {
        return Err(std::io::Error::other("synthetic directory sync failure"));
    }
    std::fs::File::open(path).and_then(|file| file.sync_all())
}

#[cfg(all(test, unix))]
pub(crate) mod fault {
    use std::cell::Cell;
    thread_local! {
        static SYNCS_BEFORE_FAILURE: Cell<Option<usize>> = const { Cell::new(None) };
    }
    /// Fail the directory sync that follows `successes` successful ones on this thread, once.
    pub(crate) fn fail_directory_sync_after(successes: usize) {
        SYNCS_BEFORE_FAILURE.with(|remaining| remaining.set(Some(successes)));
    }
    pub(crate) fn clear() {
        SYNCS_BEFORE_FAILURE.with(|remaining| remaining.set(None));
    }
    pub(super) fn directory_sync_fails() -> bool {
        SYNCS_BEFORE_FAILURE.with(|remaining| match remaining.get() {
            Some(0) => {
                remaining.set(None);
                true
            }
            Some(count) => {
                remaining.set(Some(count - 1));
                false
            }
            None => false,
        })
    }
}

fn increment(revision: u64) -> Result<u64, QueueError> {
    revision
        .checked_add(1)
        .ok_or_else(|| capacity("Queue revision is exhausted"))
}
fn now_ms() -> i64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .map(|duration| duration.as_millis().min(i64::MAX as u128) as i64)
        .unwrap_or(0)
}
fn valid_text(text: &str, limits: Limits) -> Result<(), QueueError> {
    if text.trim().is_empty()
        || text.contains('\0')
        || text.len() > limits.text_bytes
        || text.chars().count() > MAX_TEXT_CHARS
    {
        return Err(invalid(
            "Queue text is empty, contains NUL, or exceeds the supported size",
        ));
    }
    Ok(())
}
fn valid_uuid(id: Uuid) -> Result<(), QueueError> {
    if id.is_nil() {
        Err(invalid("A nonempty UUID is required"))
    } else {
        Ok(())
    }
}
fn valid_receipt(receipt: &AcceptedReceipt) -> Result<(), QueueError> {
    valid_uuid(receipt.request_id)?;
    for identifier in [&receipt.turn_id, &receipt.message_id] {
        if identifier.is_empty()
            || identifier.len() > 256
            || identifier.chars().any(char::is_control)
        {
            return Err(invalid(
                "Accepted receipt has an invalid message or turn identity",
            ));
        }
    }
    if receipt.accepted_seq == 0 {
        return Err(invalid("Accepted receipt has no canonical sequence"));
    }
    Ok(())
}
fn validate_operation(mutation: &Mutation, limits: Limits) -> Result<(), QueueError> {
    valid_uuid(mutation.operation_id)?;
    match &mutation.operation {
        QueueOperation::Enqueue { item_id, text, .. }
        | QueueOperation::Edit { item_id, text, .. } => {
            valid_uuid(*item_id)?;
            valid_text(text, limits)?;
        }
        QueueOperation::Remove { item_id, .. } | QueueOperation::Promote { item_id, .. } => {
            valid_uuid(*item_id)?
        }
        QueueOperation::Reorder { item_ids } => {
            if item_ids.len() > limits.items {
                return Err(invalid("Queue order exceeds the item limit"));
            }
            for id in item_ids {
                valid_uuid(*id)?;
            }
        }
        QueueOperation::Pause | QueueOperation::Resume | QueueOperation::Wake => {}
    }
    Ok(())
}
fn validate_scope(scope: &QueueScope) -> Result<(), QueueError> {
    let validated =
        QueueScope::new_native(&scope.owner, &scope.workspace, &scope.parent_session_id)?;
    if validated.workspace != scope.workspace {
        return Err(invalid("Queue workspace must be canonical"));
    }
    Ok(())
}
fn validate_envelope(
    envelope: &Envelope,
    scope: &QueueScope,
    limits: Limits,
) -> Result<(), QueueError> {
    use std::collections::HashSet;
    if envelope.schema_version != SCHEMA_VERSION
        || envelope.owner != scope.owner
        || envelope.workspace
            != scope
                .workspace
                .to_str()
                .ok_or_else(|| invalid("Workspace must be UTF-8"))?
        || envelope.parent_session_id != scope.parent_session_id
        || envelope.last_boot_id.is_nil()
    {
        return Err(corrupt(
            "Queue identity or schema does not match its parent scope",
        ));
    }
    if envelope
        .queue_identity
        .is_some_and(|identity| identity.is_nil())
    {
        return Err(corrupt("Queue identity is invalid"));
    }
    if envelope
        .queue_authority_installation
        .is_some_and(|identity| identity.is_nil())
        || (envelope.queue_authority_installation.is_some() && envelope.queue_identity.is_none())
    {
        return Err(corrupt("Queue authority installation identity is invalid"));
    }
    let queue = &envelope.queue;
    if queue.items.len() > limits.items || envelope.operation_receipts.len() > limits.mutations {
        return Err(corrupt("Stored queue exceeds its item or receipt limit"));
    }
    if (queue.mode == QueueMode::Held) != queue.hold_reason.is_some() {
        return Err(corrupt("Stored queue hold state is invalid"));
    }
    let mut ids = HashSet::new();
    let mut requests = HashSet::new();
    let mut pending = HashSet::new();
    let mut dispatching = 0;
    for item in &queue.items {
        if item.item_id.is_nil()
            || item.input_request_id.is_nil()
            || !ids.insert(item.item_id)
            || !requests.insert(item.input_request_id)
            || item.revision == 0
            || item.revision > queue.revision
            || item.created_at < 0
            || item.updated_at < item.created_at
            || valid_text(&item.text, limits).is_err()
        {
            return Err(corrupt("Stored queue item is invalid"));
        }
        match item.state {
            ItemState::Pending => {
                pending.insert(item.item_id);
            }
            ItemState::Dispatching => {
                dispatching += 1;
            }
            ItemState::Accepted => {
                let receipt = item
                    .accepted_receipt
                    .as_ref()
                    .ok_or_else(|| corrupt("Accepted queue item has no receipt"))?;
                if valid_receipt(receipt).is_err() || receipt.request_id != item.input_request_id {
                    return Err(corrupt("Accepted queue receipt does not match its input"));
                }
            }
            ItemState::Removed => {}
        }
        if item.state != ItemState::Accepted && item.accepted_receipt.is_some() {
            return Err(corrupt("Unaccepted queue item has an accepted receipt"));
        }
    }
    if dispatching > 1 {
        return Err(corrupt(
            "Stored queue has more than one dispatch reservation",
        ));
    }
    let order: HashSet<_> = queue.order.iter().copied().collect();
    if order.len() != queue.order.len() || order != pending {
        return Err(corrupt("Stored queue order does not match pending items"));
    }
    if !envelope.authority_proofs.is_empty() && envelope.queue_identity.is_none() {
        return Err(corrupt("Authorized queue identity is missing"));
    }
    for (item_id, proof) in &envelope.authority_proofs {
        if !(proof.starts_with("enc:v2:") || proof.starts_with("queue:v1:enc:v2:"))
            || (proof.starts_with("queue:v1:") && envelope.queue_authority_installation.is_none())
            || proof.len() > 8192
            || !queue.items.iter().any(|item| {
                item.item_id == *item_id
                    && matches!(item.state, ItemState::Pending | ItemState::Dispatching)
            })
        {
            return Err(corrupt("Stored queue authority is invalid"));
        }
    }
    for (operation_id, record) in &envelope.operation_receipts {
        let receipt = &record.receipt;
        if operation_id.is_nil()
            || *operation_id != receipt.operation_id
            || receipt.queue_revision == 0
            || receipt.queue_revision > queue.revision
            || record.payload_hash.len() != 64
            || !record
                .payload_hash
                .bytes()
                .all(|byte| byte.is_ascii_digit() || (b'a'..=b'f').contains(&byte))
        {
            return Err(corrupt("Stored operation receipt is invalid"));
        }
        match (receipt.item_id, receipt.item_revision) {
            (None, None) => {}
            (Some(item_id), Some(revision))
                if queue.items.iter().any(|item| {
                    item.item_id == item_id && revision > 0 && revision <= item.revision
                }) => {}
            _ => {
                return Err(corrupt(
                    "Stored operation receipt has an invalid item revision",
                ))
            }
        }
    }
    Ok(())
}
fn private_directory(path: &Path) -> Result<(), QueueError> {
    match std::fs::symlink_metadata(path) {
        Ok(metadata) if metadata.file_type().is_symlink() || !metadata.is_dir() => {
            return Err(corrupt("Queue store directory is unsafe"))
        }
        Ok(_) => {}
        Err(error) if error.kind() == std::io::ErrorKind::NotFound => {
            let mut builder = std::fs::DirBuilder::new();
            #[cfg(unix)]
            {
                use std::os::unix::fs::DirBuilderExt;
                builder.mode(0o700);
            }
            builder
                .create(path)
                .map_err(|_| unavailable("Cannot create private queue directory"))?;
        }
        Err(_) => return Err(unavailable("Cannot inspect private queue directory")),
    }
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o700))
            .map_err(|_| unavailable("Cannot protect private queue directory"))?;
    }
    Ok(())
}
fn empty_snapshot() -> QueueSnapshot {
    QueueSnapshot {
        revision: 0,
        mode: QueueMode::Held,
        hold_reason: Some(HoldReason::New),
        items: Vec::new(),
        order: Vec::new(),
    }
}
impl QueueStore {
    fn existing_path(&self, scope: &QueueScope) -> Result<Option<PathBuf>, QueueError> {
        let path = self.existing_path_readonly(scope)?;
        if let Some(path) = &path {
            let workspace = path.parent().ok_or_else(|| corrupt("Invalid queue path"))?;
            let owner = workspace
                .parent()
                .ok_or_else(|| corrupt("Invalid queue path"))?;
            let base = owner
                .parent()
                .ok_or_else(|| corrupt("Invalid queue path"))?;
            for directory in [base, owner, workspace] {
                private_directory(directory)?;
            }
        }
        Ok(path)
    }
    fn existing_path_readonly(&self, scope: &QueueScope) -> Result<Option<PathBuf>, QueueError> {
        validate_scope(scope)?;
        valid_uuid(self.boot_id)?;
        let metadata = std::fs::symlink_metadata(&self.data)
            .map_err(|_| unavailable("Queue data directory is unavailable"))?;
        if metadata.file_type().is_symlink() || !metadata.is_dir() {
            return Err(corrupt("Queue data directory is unsafe"));
        }
        let root = self
            .data
            .canonicalize()
            .map_err(|_| unavailable("Queue data directory is unavailable"))?;
        let base = root.join("followup-queues");
        let owner = base.join(digest(scope.owner.as_bytes()));
        let workspace = owner.join(digest(
            scope
                .workspace
                .to_str()
                .ok_or_else(|| invalid("Workspace must be UTF-8"))?
                .as_bytes(),
        ));
        for directory in [&base, &owner, &workspace] {
            match std::fs::symlink_metadata(directory) {
                Ok(metadata) if metadata.file_type().is_symlink() || !metadata.is_dir() => {
                    return Err(corrupt("Queue store directory is unsafe"))
                }
                Ok(_) => {}
                Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(None),
                Err(_) => return Err(unavailable("Cannot inspect private queue directory")),
            }
        }
        Ok(Some(
            workspace.join(format!("{}.json", scope.parent_session_id)),
        ))
    }
    fn path(&self, scope: &QueueScope) -> Result<PathBuf, QueueError> {
        validate_scope(scope)?;
        valid_uuid(self.boot_id)?;
        let root_metadata = std::fs::symlink_metadata(&self.data)
            .map_err(|_| unavailable("Queue data directory is unavailable"))?;
        if root_metadata.file_type().is_symlink() || !root_metadata.is_dir() {
            return Err(corrupt("Queue data directory is unsafe"));
        }
        let root = self
            .data
            .canonicalize()
            .map_err(|_| unavailable("Queue data directory is unavailable"))?;
        let base = root.join("followup-queues");
        private_directory(&base)?;
        let owner = base.join(digest(scope.owner.as_bytes()));
        private_directory(&owner)?;
        let workspace = owner.join(digest(
            scope
                .workspace
                .to_str()
                .ok_or_else(|| invalid("Workspace must be UTF-8"))?
                .as_bytes(),
        ));
        private_directory(&workspace)?;
        Ok(workspace.join(format!("{}.json", scope.parent_session_id)))
    }
    fn read(&self, path: &Path, scope: &QueueScope) -> Result<Option<Envelope>, QueueError> {
        use std::io::Read;
        let metadata = match std::fs::symlink_metadata(path) {
            Ok(metadata) => metadata,
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => return Ok(None),
            Err(_) => return Err(unavailable("Cannot inspect queue file")),
        };
        if metadata.file_type().is_symlink()
            || !metadata.is_file()
            || metadata.len() > self.limits.file_bytes as u64
        {
            return Err(corrupt("Queue file is unsafe or exceeds its byte limit"));
        }
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            if metadata.permissions().mode() & 0o077 != 0 {
                return Err(corrupt("Queue file is not private"));
            }
        }
        let mut options = std::fs::OpenOptions::new();
        options.read(true);
        #[cfg(unix)]
        {
            use std::os::unix::fs::OpenOptionsExt;
            options.custom_flags(libc::O_NOFOLLOW | libc::O_CLOEXEC);
        }
        let file = options
            .open(path)
            .map_err(|_| unavailable("Cannot open queue file"))?;
        if !file
            .metadata()
            .map_err(|_| unavailable("Cannot inspect opened queue file"))?
            .is_file()
        {
            return Err(corrupt("Queue file is not regular"));
        }
        let mut bytes = Vec::new();
        file.take(self.limits.file_bytes as u64 + 1)
            .read_to_end(&mut bytes)
            .map_err(|_| unavailable("Cannot read queue file"))?;
        if bytes.len() > self.limits.file_bytes {
            return Err(corrupt("Queue file exceeds its byte limit"));
        }
        let envelope: Envelope = serde_json::from_slice(&bytes)
            .map_err(|_| corrupt("Queue file is malformed; existing bytes were preserved"))?;
        validate_envelope(&envelope, scope, self.limits)?;
        Ok(Some(envelope))
    }
    fn commit(
        &self,
        path: &Path,
        envelope: &Envelope,
        scope: &QueueScope,
    ) -> Result<(), QueueError> {
        self.commit_checked(path, envelope, scope, None)
    }

    fn commit_checked(
        &self,
        path: &Path,
        envelope: &Envelope,
        scope: &QueueScope,
        check: Option<&dyn Fn() -> Result<(), String>>,
    ) -> Result<(), QueueError> {
        use std::io::Write;
        validate_envelope(envelope, scope, self.limits)?;
        let bytes = serde_json::to_vec(envelope).map_err(|_| unavailable("Cannot encode queue"))?;
        let future = envelope
            .queue
            .items
            .iter()
            .filter(|item| matches!(item.state, ItemState::Pending | ItemState::Dispatching))
            .count()
            .checked_mul(ACCEPTANCE_HEADROOM)
            .ok_or_else(|| capacity("Queue byte reservation overflow"))?;
        if bytes
            .len()
            .checked_add(future)
            .is_none_or(|size| size > self.limits.file_bytes)
        {
            return Err(capacity(
                "Queue byte capacity reached; no existing data was changed",
            ));
        }
        match std::fs::symlink_metadata(path) {
            Ok(metadata) if metadata.file_type().is_symlink() || !metadata.is_file() => {
                return Err(corrupt("Queue file is unsafe"))
            }
            Ok(_) => {}
            Err(error) if error.kind() == std::io::ErrorKind::NotFound => {}
            Err(_) => return Err(unavailable("Cannot inspect queue destination")),
        }
        let directory = path
            .parent()
            .ok_or_else(|| unavailable("Queue destination has no directory"))?;
        let mut temporary = tempfile::NamedTempFile::new_in(directory)
            .map_err(|_| unavailable("Cannot prepare queue transaction"))?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            temporary
                .as_file()
                .set_permissions(std::fs::Permissions::from_mode(0o600))
                .map_err(|_| unavailable("Cannot protect queue transaction"))?;
        }
        temporary
            .write_all(&bytes)
            .and_then(|_| temporary.as_file().sync_all())
            .map_err(|_| unavailable("Cannot write queue transaction"))?;
        if let Some(check) = check {
            check().map_err(|error| conflict(&error))?;
        }
        temporary
            .persist(path)
            .map_err(|_| unavailable("Cannot publish queue transaction"))?;
        #[cfg(unix)]
        {
            sync_directory(directory).map_err(|_| unavailable("Queue published but directory sync could not be confirmed; check operation receipt"))?;
        }
        Ok(())
    }
    fn load_locked(&self, scope: &QueueScope) -> Result<(PathBuf, Envelope), QueueError> {
        self.load_locked_checked(scope, None)
    }
    fn load_locked_checked(
        &self,
        scope: &QueueScope,
        check: Option<&dyn Fn() -> Result<(), String>>,
    ) -> Result<(PathBuf, Envelope), QueueError> {
        let path = self.path(scope)?;
        let envelope = self.read(&path, scope)?;
        match envelope {
            Some(mut envelope) => {
                if envelope.last_boot_id != self.boot_id {
                    envelope.last_boot_id = self.boot_id;
                    envelope.queue.revision = increment(envelope.queue.revision)?;
                    envelope.queue.mode = QueueMode::Held;
                    envelope.queue.hold_reason = Some(HoldReason::Restart);
                    self.commit_checked(&path, &envelope, scope, check)?;
                }
                Ok((path, envelope))
            }
            None => {
                let envelope = Envelope {
                    schema_version: SCHEMA_VERSION,
                    owner: scope.owner.clone(),
                    workspace: scope
                        .workspace
                        .to_str()
                        .ok_or_else(|| invalid("Workspace must be UTF-8"))?
                        .into(),
                    parent_session_id: scope.parent_session_id.clone(),
                    last_boot_id: self.boot_id,
                    queue_identity: None,
                    queue_authority_installation: None,
                    authority_proofs: std::collections::BTreeMap::new(),
                    queue: QueueSnapshot {
                        revision: 0,
                        mode: QueueMode::Held,
                        hold_reason: Some(HoldReason::New),
                        items: Vec::new(),
                        order: Vec::new(),
                    },
                    operation_receipts: std::collections::BTreeMap::new(),
                };
                self.commit_checked(&path, &envelope, scope, check)?;
                Ok((path, envelope))
            }
        }
    }
}

