//! Original V4 follow-up queue state and durable dispatch outbox.
//!
//! This module performs no model, terminal, HTTP, or attachment I/O. A manager
//! must authenticate the parent structured session before constructing a scope,
//! serialize queue work with that session's actor, and reconcile reservations
//! against the canonical input request journal before allowing another dispatch.
//!
//! Uses one in-process store lock and, on Unix, a fail-fast advisory lock on the
//! existing data directory for cooperating processes. This is not a session
//! lifecycle lease: the configured data directory still requires one API writer.

use serde::{Deserialize, Serialize};
use std::path::{Path, PathBuf};
use uuid::Uuid;

#[cfg(unix)]
mod authority_installation;

#[derive(Clone, Debug, PartialEq, Eq)]
pub(crate) enum QueueError {
    Invalid(String),
    Conflict(String),
    Capacity(String),
    Corrupt(String),
    Unavailable(String),
}

#[cfg(unix)]
struct QueueRootLock(std::fs::File);

#[cfg(unix)]
impl Drop for QueueRootLock {
    fn drop(&mut self) {
        let _ = self.0.unlock();
    }
}

#[derive(Clone, Debug)]
pub(crate) struct QueueScope {
    owner: String,
    workspace: PathBuf,
    parent_session_id: String,
}
impl QueueScope {
    pub(crate) fn workspace(&self) -> &Path {
        &self.workspace
    }

    /// Call only after authenticating the exact native session ID; UUID spellings remain distinct records.
    pub(crate) fn new_native(
        owner: &str,
        workspace: &Path,
        parent_session_id: &str,
    ) -> Result<Self, QueueError> {
        Self::new_with_formats(owner, workspace, parent_session_id, true)
    }

    pub(crate) fn new(
        owner: &str,
        workspace: &Path,
        parent_session_id: &str,
    ) -> Result<Self, QueueError> {
        Self::new_with_formats(owner, workspace, parent_session_id, false)
    }

    fn new_with_formats(
        owner: &str,
        workspace: &Path,
        parent_session_id: &str,
        allow_hyphenated: bool,
    ) -> Result<Self, QueueError> {
        if owner.trim().is_empty()
            || owner.len() > MAX_OWNER_BYTES
            || owner.chars().any(char::is_control)
        {
            return Err(invalid("Invalid queue account identity"));
        }
        let suffix = parent_session_id
            .strip_prefix("ss-")
            .ok_or_else(|| invalid("Invalid parent session ID"))?;
        let parsed = Uuid::parse_str(suffix).map_err(|_| invalid("Invalid parent session UUID"))?;
        let simple_uuid = parsed.simple().to_string();
        let compact = suffix == simple_uuid
            || (allow_hyphenated && suffix.eq_ignore_ascii_case(&simple_uuid));
        let hyphenated =
            allow_hyphenated && suffix.eq_ignore_ascii_case(&parsed.hyphenated().to_string());
        if parsed.is_nil() || !(compact || hyphenated) {
            return Err(invalid(if allow_hyphenated {
                "Parent session ID must use a simple or hyphenated UUID format"
            } else {
                "Parent session ID must be canonical ss-UUID simple format"
            }));
        }
        if !workspace.is_absolute() {
            return Err(invalid("Queue workspace must be absolute"));
        }
        let workspace = workspace
            .canonicalize()
            .map_err(|_| invalid("Queue workspace is unavailable"))?;
        if !workspace.is_dir() || workspace.to_str().is_none() {
            return Err(invalid("Queue workspace must be a UTF-8 directory"));
        }
        Ok(Self {
            owner: owner.into(),
            workspace,
            parent_session_id: parent_session_id.into(),
        })
    }
}

