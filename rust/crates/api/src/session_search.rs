#[derive(Default, Deserialize)]
#[serde(rename_all = "camelCase")]
struct SearchQuery {
    q: Option<String>,
    path: Option<String>,
    limit: Option<usize>,
}

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct SessionSearchResult {
    pub session_id: String,
    pub kind: String,
    pub title: String,
    pub workspace_path: String,
    pub updated_at: String,
    pub snippet: String,
    pub match_type: &'static str,
    pub anchor: Option<MessageAnchor>,
}

#[derive(Debug, Clone, Serialize, PartialEq)]
#[serde(rename_all = "camelCase")]
pub struct MessageAnchor {
    #[serde(rename = "type")]
    pub kind: &'static str,
    pub message_id: String,
    pub role: String,
}

pub fn routes() -> Router<AppState> {
    Router::new()
        .route("/api/workspace/history", axum::routing::get(search))
        .layer(axum::middleware::map_response(private_response))
}

fn validate_query(query: &SearchQuery) -> Result<(), ApiError> {
    if query
        .q
        .as_ref()
        .is_some_and(|q| q.chars().count() > 256 || q.chars().any(char::is_control))
        || query
            .path
            .as_ref()
            .is_some_and(|path| path.len() > 2048 || !std::path::Path::new(path).is_absolute())
        || query.limit.is_some_and(|limit| limit == 0 || limit > 50)
    {
        return Err(ApiError::bad_request(
            "Search accepts up to 256 characters, an absolute workspace path, and 1–50 results",
        ));
    }
    Ok(())
}

pub(crate) fn safe_history_text(text: &str) -> String {
    use regex_lite::Regex;
    use std::sync::OnceLock;
    static TERMINAL: OnceLock<Regex> = OnceLock::new();
    static SECRET_LINE: OnceLock<Regex> = OnceLock::new();
    static TOKEN: OnceLock<Regex> = OnceLock::new();
    static URL_AUTH: OnceLock<Regex> = OnceLock::new();
    static PRIVATE_KEY: OnceLock<Regex> = OnceLock::new();
    let terminal = TERMINAL.get_or_init(|| {
        Regex::new(r"\x1b(?:\[[0-?]*[ -/]*[@-~]|\][^\x07]*(?:\x07|\x1b\\))").unwrap()
    });
    let secret = SECRET_LINE.get_or_init(|| {
        Regex::new(r"(?i)\b(?:[a-z0-9_]*(?:api_key|token|secret|password)|authorization)\s*[:=]")
            .unwrap()
    });
    let token = TOKEN.get_or_init(|| Regex::new(r"\b(?:sk-[a-zA-Z0-9_-]+|gh[pousr]_[a-zA-Z0-9_]+|eyJ[a-zA-Z0-9_-]+\.[a-zA-Z0-9_-]+\.[a-zA-Z0-9_-]+)").unwrap());
    let url_auth = URL_AUTH.get_or_init(|| Regex::new(r"https?://[^/\s:@]+:[^/\s@]+@").unwrap());
    let private_key=PRIVATE_KEY.get_or_init(||Regex::new(r"(?s)-----BEGIN [A-Z0-9 ]*PRIVATE KEY(?: BLOCK)?-----.*?(?:-----END [A-Z0-9 ]*PRIVATE KEY(?: BLOCK)?-----|$)").unwrap());
    let clean = if text.contains('\x1b') {
        terminal.replace_all(text, "")
    } else {
        std::borrow::Cow::Borrowed(text)
    };
    let clean = if clean.contains("PRIVATE KEY") {
        private_key.replace_all(&clean, "[redacted]")
    } else {
        std::borrow::Cow::Borrowed(clean.as_ref())
    };
    clean
        .lines()
        .map(|line| {
            let possible_secret = line.contains([':', '='])
                && (!line.is_ascii() || {
                    let lower = line.to_ascii_lowercase();
                    ["api_key", "token", "secret", "password", "authorization"]
                        .iter()
                        .any(|marker| lower.contains(marker))
                });
            if possible_secret && secret.is_match(line) {
                "[redacted]".to_string()
            } else {
                let value = if line.contains("sk-") || line.contains("gh") || line.contains("eyJ") {
                    token.replace_all(line, "[redacted]")
                } else {
                    std::borrow::Cow::Borrowed(line)
                };
                let value = if value.contains("://") && value.contains('@') {
                    url_auth.replace_all(&value, "[redacted]@")
                } else {
                    std::borrow::Cow::Borrowed(value.as_ref())
                };
                value
                    .chars()
                    .filter(|c| !c.is_control() || *c == '\t')
                    .collect()
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn snippet(text: &str, query: &str) -> Option<String> {
    let normalized = text.split_whitespace().collect::<Vec<_>>().join(" ");
    let mut lower = String::new();
    let mut source_chars = Vec::new();
    for (index, character) in normalized.chars().enumerate() {
        for lowered in character.to_lowercase() {
            source_chars.extend(std::iter::repeat_n(index, lowered.len_utf8()));
            lower.push(lowered);
        }
    }
    // Redaction markers are generated by the server, not matches in history.
    let searchable = lower.replace("[redacted]", &"\0".repeat("[redacted]".len()));
    let needle = query.trim().to_lowercase();
    let byte_index = if needle.is_empty() {
        0
    } else {
        searchable.find(&needle)?
    };
    let match_chars = source_chars.get(byte_index).copied().unwrap_or(0);
    let characters: Vec<char> = normalized.chars().collect();
    let start = match_chars
        .saturating_sub(72)
        .min(characters.len().saturating_sub(240));
    let end = (start + 240).min(characters.len());
    Some(format!(
        "{}{}{}",
        if start > 0 { "…" } else { "" },
        characters[start..end].iter().collect::<String>(),
        if end < characters.len() { "…" } else { "" }
    ))
}

fn structured_match(
    events: &[terminal_v4_core::StructuredSessionEvent],
    query: &str,
) -> Option<(String, Option<MessageAnchor>)> {
    use terminal_v4_core::StructuredSessionEvent;

    let mut messages: Vec<(&str, Option<&str>, Option<&str>, &str)> = Vec::new();
    for event in events {
        let (role, message_id, request_id, content) = match event {
            StructuredSessionEvent::UserMessageAccepted {
                message_id,
                request_id,
                content,
                ..
            } => (
                "user",
                Some(message_id.as_str()),
                Some(request_id.as_str()),
                content.as_str(),
            ),
            StructuredSessionEvent::MessageCompleted {
                role,
                message_id,
                content,
                ..
            } if role == "user" || role == "assistant" => {
                (role.as_str(), message_id.as_deref(), None, content.as_str())
            }
            _ => continue,
        };
        let existing = messages
            .iter()
            .position(|(old_role, old_id, old_request, _)| {
                *old_role == role
                    && (message_id
                        .filter(|id| !id.is_empty())
                        .is_some_and(|id| Some(id) == *old_id)
                        || request_id
                            .filter(|id| !id.is_empty())
                            .is_some_and(|id| Some(id) == *old_request))
            });
        if let Some(index) = existing {
            let previous_request = messages[index].2;
            messages[index] = (role, message_id, request_id.or(previous_request), content);
        } else {
            messages.push((role, message_id, request_id, content));
        }
    }

    // A private key can span persisted records. Suppress message results for
    // this session rather than redacting each record in isolation and leaking it.
    static BEGIN_KEY: std::sync::OnceLock<regex_lite::Regex> = std::sync::OnceLock::new();
    static COMPLETE_KEY: std::sync::OnceLock<regex_lite::Regex> = std::sync::OnceLock::new();
    let begin_key = BEGIN_KEY.get_or_init(|| {
        regex_lite::Regex::new(r"-----BEGIN [A-Z0-9 ]*PRIVATE KEY(?: BLOCK)?-----").unwrap()
    });
    let complete_key = COMPLETE_KEY.get_or_init(|| regex_lite::Regex::new(r"(?s)-----BEGIN [A-Z0-9 ]*PRIVATE KEY(?: BLOCK)?-----.*?-----END [A-Z0-9 ]*PRIVATE KEY(?: BLOCK)?-----").unwrap());
    if messages
        .iter()
        .any(|(_, _, _, content)| begin_key.is_match(&complete_key.replace_all(content, "")))
    {
        return None;
    }
    messages
        .into_iter()
        .find_map(|(role, message_id, _, content)| {
            let clean = safe_history_text(content);
            if clean.trim().is_empty() {
                return None;
            }
            snippet(&clean, query).map(|found| {
                let anchor = message_id
                    .filter(|id| !id.is_empty())
                    .map(|id| MessageAnchor {
                        kind: "message",
                        message_id: id.to_string(),
                        role: role.to_string(),
                    });
                (found, anchor)
            })
        })
}

async fn search(
    State(state): State<AppState>,
    Extension(user): Extension<AuthenticatedUser>,
    Query(query): Query<SearchQuery>,
) -> Result<Json<Vec<SessionSearchResult>>, ApiError> {
    validate_query(&query)?;
    let search_text = query.q.as_deref().unwrap_or("").trim();
    let filter = query.path.as_deref().map(workspace_filter_key);
    let state_for_io = state.clone();
    let owner = user.clone();
    let terminals =
        tokio::task::spawn_blocking(move || state_for_io.list_terminal_sessions(&owner))
            .await
            .map_err(|_| ApiError::internal("Unable to load saved conversations"))?
            .map_err(|_| ApiError::internal("Unable to load saved conversations"))?;
    let mut results = Vec::new();
    for session in terminals {
        let path = session
            .thread
            .as_ref()
            .and_then(|thread| thread.project_path.as_deref())
            .unwrap_or(&session.cwd);
        if filter
            .as_ref()
            .is_some_and(|value| *value != workspace_filter_key(path))
        {
            continue;
        }
        let snapshot = state
            .terminal_manager()
            .get_session_history(
                &user.user_id,
                &session.id,
                &crate::state::HistoryQuery::default(),
            )
            .await
            .map_err(|_| ApiError::internal("Unable to load saved conversation"))?;
        let body = snapshot
            .map(|value| {
                value
                    .history
                    .into_iter()
                    .map(|event| event.text)
                    .collect::<Vec<_>>()
                    .join("")
            })
            .unwrap_or_default();
        let title = safe_history_text(&session.title);
        let cleaned = safe_history_text(&body);
        let body_match = (!cleaned.trim().is_empty())
            .then(|| snippet(&cleaned, search_text))
            .flatten();
        let title_match = || snippet(&title, search_text);
        let matched = if search_text.is_empty() {
            body_match
                .or_else(title_match)
                .map(|found| (found, "recent"))
        } else {
            body_match
                .map(|found| (found, "terminal_output"))
                .or_else(|| title_match().map(|found| (found, "title")))
        };
        if let Some((found, match_type)) = matched {
            results.push(SessionSearchResult {
                session_id: session.id,
                kind: "terminal".into(),
                title,
                workspace_path: path.to_string(),
                updated_at: session.updated_at,
                snippet: found,
                match_type,
                anchor: None,
            });
        }
    }
    for session in state
        .structured_session_manager()
        .list_sessions(&user.user_id)
        .await
        .map_err(|_| ApiError::internal("Unable to load saved conversations"))?
    {
        let path = session
            .thread
            .as_ref()
            .and_then(|thread| thread.project_path.as_deref())
            .unwrap_or(&session.cwd);
        if filter
            .as_ref()
            .is_some_and(|value| *value != workspace_filter_key(path))
        {
            continue;
        }
        let title = safe_history_text(&session.title);
        let body_match = structured_match(&session.events, search_text);
        let matched = if search_text.is_empty() {
            body_match
                .map(|(found, _)| (found, "recent", None))
                .or_else(|| snippet(&title, search_text).map(|found| (found, "recent", None)))
        } else {
            body_match
                .map(|(found, anchor)| (found, "message", anchor))
                .or_else(|| snippet(&title, search_text).map(|found| (found, "title", None)))
        };
        if let Some((found, match_type, anchor)) = matched {
            results.push(SessionSearchResult {
                session_id: session.id,
                kind: "structured".into(),
                title,
                workspace_path: path.to_string(),
                updated_at: session.updated_at,
                snippet: found,
                match_type,
                anchor,
            });
        }
    }
    results.sort_by(|left, right| {
        right
            .updated_at
            .cmp(&left.updated_at)
            .then_with(|| left.session_id.cmp(&right.session_id))
    });
    results.truncate(query.limit.unwrap_or(20));
    Ok(Json(results))
}

pub(crate) fn workspace_filter_key(path: &str) -> String {
    match std::fs::canonicalize(path) {
        Ok(canonical) => normalize_workspace_path(&canonical.to_string_lossy()),
        // Missing or unmounted workspaces still match their saved spelling.
        Err(_) => normalize_workspace_path(path),
    }
}

pub(crate) fn normalize_workspace_path(path: &str) -> String {
    let normalized = path.replace('\\', "/").trim_end_matches('/').to_string();
    if cfg!(windows) {
        normalized.to_lowercase()
    } else {
        normalized
    }
}

